//! # AgentPay Smart Account
//!
//! A Soroban smart account representing an AI agent's wallet, built on
//! OpenZeppelin's `stellar-accounts` framework. It uses context rules to
//! scope authorization per vendor contract, and spending-limit policies
//! to enforce per-period spend caps.
//!
//! ## Architecture
//!
//! - One `ContextRule` per allowed vendor/resource contract
//!   (`ContextRuleType::CallContract`).
//! - A `SpendingLimitPolicy` attached to each rule, enforcing a
//!   max-spend-per-period cap.
//! - An admin entrypoint `apply_policy` installs rules + policies from
//!   a `PolicySpec` generated by the Python policy generator.
//! - Events emitted on every authorization decision for audit.

